#!/usr/bin/env python3
"""Generate text-based résumé PDFs for First Impression AI local testing."""

from pathlib import Path
from fpdf import FPDF

OUT = Path(__file__).resolve().parent


class ResumePDF(FPDF):
    def __init__(self, footer_label: str):
        super().__init__(format="Letter")
        self.footer_label = footer_label
        self.set_auto_page_break(auto=True, margin=18)
        self.add_page()
        self.set_left_margin(18)
        self.set_right_margin(18)

    def footer(self):
        self.set_y(-14)
        self.set_font("Helvetica", size=8)
        self.set_text_color(120)
        self.cell(0, 8, self.footer_label, align="C")

    def writeln(self, text, style="", size=10.5, color=(40, 44, 50), h=6):
        self.set_x(self.l_margin)
        self.set_font("Helvetica", style, size)
        self.set_text_color(*color)
        self.multi_cell(self.epw, h, text)

    def heading(self, title):
        self.ln(2)
        self.writeln(title, "B", 11, (30, 70, 64), 8)
        y = self.get_y()
        self.set_draw_color(30, 70, 64)
        self.line(self.l_margin, y, self.l_margin + self.epw, y)
        self.ln(2)

    def name(self, text):
        self.writeln(text, "B", 18, (20, 24, 32), 9)

    def meta(self, text):
        self.writeln(text, "", 10, (60, 64, 70), 5.5)

    def job(self, text):
        self.writeln(text, "B", 10.5, (20, 24, 32), 6)

    def dates(self, text):
        self.writeln(text, "I", 9.5, (90, 94, 100), 5)

    def body(self, text):
        self.writeln(text, "", 10.5, (40, 44, 50), 6)


def save(pdf: ResumePDF, filename: str):
    path = OUT / filename
    pdf.output(str(path))
    print(f"wrote {path.name}  ({path.stat().st_size} bytes)")


